/*
  First-contact welcome (pure, no database). The welcome block is generated by code, never by the AI,
  and appended to the first reply only after the database claim succeeded (see src/lib/welcome.ts).
*/

import { detectLanguageCode } from './language';

export type Lang = 'en' | 'ar' | 'so' | 'zh';

const SOMALI = /\b(waxaan|waxaad|ma (haysaa|haysataan|jiraa)|imisa|meeqa|baabuur|gaari|gaadhi|fadlan|mahadsanid|haa|maya|iga|ii soo|sawir|qiimaha|qiimo|xagee|goorma|salaan|nabad|walaal|soo dir|rabaa|doonayaa|iyo|waa|ka|ku|la|aan|aad|tahay|yahay)\b/gi;

/** Customer's language from their own words: Arabic script → ar, enough Somali words → so, else en. */
/** Shared detector (src/lib/ai-rules/language.ts). One distinctive Somali word is enough now. */
export function detectLanguage(text: string, fallback: Lang = 'en'): Lang {
  const code = detectLanguageCode(String(text || ''));
  return (code || fallback) as Lang;
}

/** Previous heuristic, kept for reference (no longer used). */
function detectLanguageLegacy(text: string, fallback: Lang = 'en'): Lang {
  const t = String(text || '');
  if (!t.trim()) return fallback;
  const arabic = (t.match(/[؀-ۿ]/g) || []).length;
  const latin = (t.match(/[A-Za-z]/g) || []).length;
  if (arabic > 0 && arabic >= latin) return 'ar';
  const so = (t.match(SOMALI) || []).length;
  const words = t.split(/\s+/).filter(Boolean).length;
  if (so >= 2 || (so >= 1 && words <= 3 && /\b(haa|maya|fadlan|mahadsanid|imisa|meeqa|salaan|walaal)\b/i.test(t))) return 'so';
  return latin ? 'en' : fallback;
}

export type WelcomeConfig = { enabled: boolean; site: string; groupLink: string; groupName: string };

export const DEFAULT_GROUP_LINK = 'https://chat.whatsapp.com/EyGQRCZmdyhKUnXD2H1bIq?s=cl&p=a&mlu=4&ilr=4';
export const DEFAULT_GROUP_NAME = 'Sky second hand cars';

/** Two short lines: website, then the group invitation, in the customer's language. */
export function welcomeBlock(lang: Lang, cfg: WelcomeConfig) {
  const site = cfg.site.replace(/\/$/, '');
  const lines: Record<Lang, [string, string]> = {
    en: [`See all our cars: ${site}`, `Join our WhatsApp group "${cfg.groupName}" for new arrivals: ${cfg.groupLink}`],
    ar: [`شاهد جميع سياراتنا: ${site}`, `انضم إلى مجموعتنا على واتساب "${cfg.groupName}" لأحدث السيارات: ${cfg.groupLink}`],
    so: [`Arag dhammaan baabuurtayada: ${site}`, `Ku biir kooxdayada WhatsApp "${cfg.groupName}" si aad u aragto baabuurta cusub: ${cfg.groupLink}`],
    zh: [`\u67e5\u770b\u6211\u4eec\u6240\u6709\u7684\u8f66: ${site}`, `\u52a0\u5165\u6211\u4eec\u7684 WhatsApp \u7fa4 "${cfg.groupName}"\uff0c\u53ca\u65f6\u770b\u5230\u65b0\u8f66: ${cfg.groupLink}`],
  };
  return lines[lang].join('\n');
}

/** Answer first, then the welcome block, as ONE message. */
export function withWelcome(answer: string, lang: Lang, cfg: WelcomeConfig) {
  const a = String(answer || '').trim();
  return a ? `${a}\n\n${welcomeBlock(lang, cfg)}` : welcomeBlock(lang, cfg);
}

/** Append an already-built welcome block (used when it was generated for the customer's language). */
export function withBlock(answer: string, block: string) {
  const a = String(answer || '').trim();
  const b = String(block || '').trim();
  if (!b) return a;
  return a ? `${a}\n\n${b}` : b;
}

export function askedForWebsite(text: string) {
  return /\b(website|web ?site|site|link|url|online|webka|bogga|websaydh)\b|موقع|رابط/i.test(String(text || ''));
}
export function askedForGroup(text: string) {
  return /\b(group|groups|kooxda|koox|grupo)\b|مجموعة|قروب|جروب/i.test(String(text || ''));
}

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * After the welcome: removes our website ROOT link and chat.whatsapp.com links from an AI reply,
 * unless the customer asked for the website / group. Vehicle page links (site/vehicles/123) stay.
 * Lines that are left with only a label ("Visit our website:") are removed too.
 */
export function stripPromoLinks(reply: string, opts: { site: string; allowSite?: boolean; allowGroup?: boolean }) {
  let out = String(reply || '');
  const host = opts.site.replace(/^https?:\/\//i, '').replace(/\/$/, '');
  if (!opts.allowGroup) out = out.replace(/https?:\/\/chat\.whatsapp\.com\/\S+/gi, '');
  if (!opts.allowSite) {
    const root = new RegExp(`(?:https?:\\/\\/)?(?:www\\.)?${esc(host)}\\/?(?=[\\s)\\].,!?]|$)`, 'gi');
    out = out.replace(root, '');
  }
  out = out.split('\n').filter(line => {
    const l = line.trim();
    if (!l) return true;
    // A line that only introduced a link we removed.
    // A line that only introduced a link we removed, e.g. "Visit our website:" / "Join our group -".
    return !(/[:\-–]\s*$/.test(l) && /(website|web site|\bsite\b|group|\blink\b|koox|bogga|websaydh|موقع|مجموعة|رابط)/i.test(l));
  }).join('\n');
  return out.replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').replace(/\(\s*\)/g, '').replace(/[ \t]{2,}/g, ' ').trim();
}

export function containsPromoLinks(reply: string, site: string) {
  const host = site.replace(/^https?:\/\//i, '').replace(/\/$/, '');
  return /chat\.whatsapp\.com\//i.test(reply) || new RegExp(`(?:https?:\\/\\/)?(?:www\\.)?${esc(host)}\\/?(?=[\\s)\\].,!?]|$)`, 'i').test(reply);
}
